import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';

test('department lifecycle, assignment, personal records, role isolation and revocation', async () => {
 const dir=await mkdtemp(join(tmpdir(),'ejp-journeys-'));
 const port=52000+Math.floor(Math.random()*3000);
 const child=spawn(process.execPath,['server/index.mjs'],{env:{...process.env,EJP_DATA_DIR:dir,EJP_API_PORT:String(port)},stdio:['ignore','pipe','pipe']});
 let cookie='';
 const call=async(path,data,status=200)=>{const r=await fetch(`http://127.0.0.1:${port}/api/local/${path}`,{headers:{'Content-Type':'application/json',Cookie:cookie},...(data===undefined?{}:{method:'POST',body:JSON.stringify(data)})});const value=await r.json();assert.equal(r.status,status,JSON.stringify(value));if(r.headers.get('set-cookie'))cookie=r.headers.get('set-cookie').split(';')[0];return value;};
 const entity=(name,method,...args)=>call('entities/'+name,{method,args});
 try {
  await Promise.race([once(child.stdout,'data'),once(child,'exit').then(()=>{throw Error('Startup failed');})]);
  const admin=await call('setup',{email:'testadmin@ejp.local',password:'isolated-password-123'});
  const adminCookie=cookie;
  const department=await entity('Department','create',{name:'Accueil et intégration'});
  assert.equal(department.slug,'accueil-et-integration');
  assert.equal(department.is_active,true);
  await call('entities/Department',{method:'create',args:[{name:'Accueil et intégration'}]},409);
  const person=await call('functions/adminManageUser',{action:'create',first_name:'Alice',last_name:'Audit'});
  const other=await call('functions/adminManageUser',{action:'create',first_name:'Benoit',last_name:'Audit'});
  await call('functions/adminManageUser',{action:'add_membership',user_id:person.user_id,department_id:department.id,role_in_dept:'serviteur'});
  const fiche=await call('functions/annuaireSearch',{action:'getPerson',user_id:person.user_id});
  assert.ok(JSON.stringify(fiche).includes(department.name));
  assert.equal((await call('functions/getDepartmentData',{department_slug:department.id})).access_granted,true);
  assert.equal((await call('functions/getDepartmentData',{department_slug:department.slug})).access_granted,true);
  const event=await entity('Event','create',{title:'Culte de test',event_date:'2026-12-20',is_active:true});
  const program=await entity('TrainingProgram','create',{title:'Formation de test',status:'published',is_public:true});
  const module=await entity('TrainingModule','create',{title:'Module de test',program_id:program.id});
  const resource=await entity('StarResource','create',{title:'Document de test',is_active:true});
  await call('auth/login',{email:person.internal_identifier,password:person.temporary_password});
  await call('entities/DepartmentMember',{method:'list',args:[]},403);
  await call('auth/changePassword',{currentPassword:person.temporary_password,newPassword:'alice-isolated-password-123'});
  const aliceCookie=cookie;
  assert.equal((await entity('DepartmentMember','list')).length,1);
  assert.equal((await call('functions/getDepartmentData',{department_slug:department.slug})).access_granted,true);
  const note=await entity('PersonalNote','create',{title:'Note privée',content:'Test',user_id:other.user_id,created_by_id:other.user_id});
  assert.equal(note.user_id,person.user_id);assert.equal(note.created_by_id,person.user_id);
  const attendance=await entity('AttendanceResponse','create',{event_id:event.id,status:'present'});
  assert.equal(attendance.created_by_id,person.user_id);
  await entity('AttendanceResponse','create',{event_id:event.id,status:'absent'});
  assert.equal((await entity('AttendanceResponse','list')).length,1);
  const rdv=await entity('AppointmentRequest','create',{subject:'Demande test'});assert.equal(rdv.status,'pending');
  await entity('UserWorkspacePreference','create',{accent_color:'blue'});
  assert.equal((await entity('TrainingProgram','list'))[0].id,program.id);
  assert.equal((await entity('StarResource','list'))[0].id,resource.id);
  const submission=await entity('TrainingSubmission','create',{program_id:program.id,module_id:module.id,status:'submitted',summary_text:'Résumé'});
  await call('entities/TrainingSubmission',{method:'update',args:[submission.id,{status:'validated'}]},403);
  await call('entities/DepartmentMember',{method:'create',args:[{user_id:person.user_id,department_id:department.id}]},403);
  await call('functions/adminManageUser',{action:'create',first_name:'No',last_name:'Privilege'},403);
  await call('auth/login',{email:other.internal_identifier,password:other.temporary_password});
  await call('auth/changePassword',{currentPassword:other.temporary_password,newPassword:'benoit-isolated-password-123'});
  assert.equal((await entity('PersonalNote','list')).length,0);
  assert.equal((await entity('AttendanceResponse','list')).length,0);
  await call('entities/PersonalNote',{method:'get',args:[note.id]},403);
  await call('entities/PersonalNote',{method:'update',args:[note.id,{content:'forbidden'}]},403);
  assert.equal((await call('functions/getDepartmentData',{department_slug:department.slug})).access_denied,true);
  cookie=adminCookie;
  assert.equal((await call('entities/PersonalNote',{method:'list',args:[],scope:'self'})).length,0);
  const memberships=await entity('DepartmentMember','filter',{user_id:person.user_id});
  await call('functions/adminManageUser',{action:'remove_membership',membership_id:memberships[0].id});
  cookie=aliceCookie;
  assert.equal((await call('functions/getDepartmentData',{department_slug:department.slug})).access_denied,true);
  assert.equal((await entity('PersonalNote','list')).length,1);
  cookie=adminCookie;
  await entity('User','update',other.user_id,{role:'serviteur',roles:['serviteur'],badges:['ADMIN']});
  await call('auth/login',{email:other.internal_identifier,password:'benoit-isolated-password-123'});
  assert.ok((await entity('User','list')).length>=3);
  cookie=adminCookie;
  await call('functions/adminManageUser',{action:'suspend',user_id:person.user_id});
  cookie=aliceCookie;
  await call('entities/PersonalNote',{method:'list',args:[]},401);
  assert.equal(admin.role,'admin');
 } finally { if(child.exitCode===null){const done=once(child,'exit');child.kill();await done;}await rm(dir,{recursive:true,force:true}); }
});
