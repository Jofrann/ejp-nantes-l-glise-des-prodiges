import {freePort} from './test-port.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';

test('uploads: public media, private access, resource sharing, range, persistence, first login and shop subscriptions',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'ejp-files-'));
 const port=await freePort(), base=`http://127.0.0.1:${port}`;
 let child,cookie='';
 const start=async()=>{child=spawn(process.execPath,['server/web.mjs'],{env:{...process.env,EJP_DATA_DIR:dir,PORT:String(port),EJP_HOST:'127.0.0.1',OPENAI_API_KEY:'',RESEND_API_KEY:'',GOOGLE_REFRESH_TOKEN:''},stdio:['ignore','pipe','pipe']});await Promise.race([once(child.stdout,'data'),once(child,'exit').then(()=>{throw Error('API startup failed');})]);};
 const stop=async()=>{const done=once(child,'exit');child.kill();await done;};
 const call=async(path,data,status=200)=>{const r=await fetch(base+'/api/local/'+path,{headers:{Cookie:cookie,'Content-Type':'application/json'},...(data===undefined?{}:{method:'POST',body:JSON.stringify(data)})});const value=await r.json();assert.equal(r.status,status,JSON.stringify(value));if(r.headers.get('set-cookie'))cookie=r.headers.get('set-cookie').split(';')[0];return value;};
 const entity=(name,method,...args)=>call('entities/'+name,{method,args});
 const upload=async(bytes,name,type,visibility='private',status=200)=>{const form=new FormData();form.append('file',new Blob([bytes],{type}),name);form.append('visibility',visibility);const r=await fetch(base+'/api/local/files/upload',{method:'POST',headers:{Cookie:cookie},body:form});const value=await r.json();assert.equal(r.status,status,JSON.stringify(value));return value;};
 const download=async(url,status,headers={})=>{const r=await fetch(base+url,{headers:{Cookie:cookie,...headers}});assert.equal(r.status,status);return r;};
 try {
  await start();
  const png=await readFile('public/brand/ejp-logo.png');
  await upload(png,'logo.png','image/png','private',401);
  await call('setup',{email:'admin@files.test',password:'admin-files-test-password'});
  const adminCookie=cookie;
  const publicImage=await upload(png,'logo.png','image/png','public');
  const privateDoc=await upload('%PDF-1.4\nprivate fixture','guide.pdf','application/pdf');
  await upload('<script>alert(1)</script>','bad.png','image/png','public',415);
  await upload('<svg/>','bad.svg','image/svg+xml','public',415);
  await upload('','empty.txt','text/plain','private',400);
  await upload('secret','note.txt','text/plain','public',400);
  const alice=await call('functions/adminManageUser',{action:'create',first_name:'Alice',last_name:'Upload'});
  const bob=await call('functions/adminManageUser',{action:'create',first_name:'Bob',last_name:'Upload'});
  const resource=await entity('StarResource','create',{title:'Guide',is_active:true,file_url:privateDoc.file_url});
  await call('auth/login',{email:alice.internal_identifier,password:alice.temporary_password});
  await upload(png,'test.png','image/png','private',403);
  await download(privateDoc.file_url,404);
  await call('auth/changePassword',{currentPassword:alice.temporary_password,newPassword:'alice-files-test-password'});
  const aliceCookie=cookie;
  await download(privateDoc.file_url,200);
  await upload(png,'test.png','image/png','public',403);
  const personal=await upload('private note','note.txt','text/plain');
  assert.equal(await (await download(personal.file_url,200)).text(),'private note');
  assert.equal((await download(personal.file_url,206,{Range:'bytes=0-6'})).headers.get('content-range'),'bytes 0-6/12');
  assert.equal(await (await download(personal.file_url,206,{Range:'bytes=-4'})).text(),'note');
  await download(personal.file_url,416,{Range:'bytes=999-1000'});
  await call('integrations/status',undefined,403);
  await call('integrations/InvokeLLM',{prompt:'Hello'},503);
  await call('integrations/SendEmail',{to:'test@example.org',subject:'test',body:'test'},403);
  await call('shop/subscription',{});await call('shop/subscription',{});
  const post=await entity('Post','create',{content:'Hello',author_id:bob.user_id,media_url:personal.file_url});
  assert.equal(post.author_id,alice.user_id);
  await call('entities/Post',{method:'create',args:[{content:'no',type:'announcement'}]},403);
  await call('auth/login',{email:bob.internal_identifier,password:bob.temporary_password});
  await call('auth/changePassword',{currentPassword:bob.temporary_password,newPassword:'bob-files-test-password'});
  await download(personal.file_url,200); // inherited from the readable social post
  const unshared=await upload('bob private','bob.txt','text/plain');
  cookie=aliceCookie;await download(unshared.file_url,404);
  await call('entities/Post',{method:'update',args:[post.id,{author_id:bob.user_id}]});
  assert.equal((await entity('Post','get',post.id)).author_id,alice.user_id);
  cookie=adminCookie;
  await entity('StarResource','update',resource.id,{is_active:false});
  cookie=aliceCookie;await download(privateDoc.file_url,404);
  cookie=adminCookie;
  await call('entities/StarProduct',{method:'create',args:[{name:'Bad',stripe_checkout_url:'javascript:alert(1)'}]},400);
  await entity('StarProduct','create',{name:'Produit',is_active:true,stripe_checkout_url:'https://buy.stripe.com/test_fixture'});
  await entity('StarProduct','create',{name:'Autre',is_active:true});
  cookie=aliceCookie;
  assert.equal((await entity('StarNotification','filter',{title:'La boutique EJP est ouverte'})).length,1);
  cookie=adminCookie;
  const fij=await entity('FIJ','create',{name:'FIJ fixture',status:'active',pilot_user_id:alice.user_id});
  const fijFile=await upload('%PDF-1.4 document FIJ','fij.pdf','application/pdf');
  await entity('FijDocument','create',{title:'FIJ interne',visibility:'pilots',file_url:fijFile.file_url});
  cookie=aliceCookie;await download(fijFile.file_url,200);
  cookie=adminCookie;await entity('FIJ','update',fij.id,{pilot_user_id:bob.user_id});
  cookie=aliceCookie;await download(fijFile.file_url,404);
  await stop();await start();
  assert.equal(await (await download(personal.file_url,200)).text(),'private note');
  cookie='';await download(publicImage.file_url,200);await download(privateDoc.file_url,404);await download(personal.file_url,404);
 }finally{if(child?.exitCode===null)await stop();await rm(dir,{recursive:true,force:true});}
});
